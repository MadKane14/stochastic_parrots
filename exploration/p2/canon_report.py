"""T10 (p2): held-out quality of the learned abbreviation map (`learn_canonical_map`) and junk tokens (`learn_junk`).

Protocol: maps learned from true pairs of S1 with unit_hash(s1, 5) in [0.1, 0.1 + FIT) (laptop memory: a sample
of the fit side), evaluated on the held-out pairs of S1 with hash < 0.1 (the same queries blk_eval uses). The native
map (variant D: no folding) is learned on the same fit pairs and applied first, as in the normalizer.
Precision check: the change in token Jaccard is reported for TRUE held-out pairs and for RANDOM pairs (each held-out
S1 with the S2/S3 record of another held-out pair, same country) — a useful normalization raises the first, not the second.

Usage: python exploration/p2/canon_report.py [--fit 0.3] > exploration/p2/canon_out.md
"""
from __future__ import annotations

import argparse
import sys
import time
from collections import Counter
from pathlib import Path

import numpy as np
import pyarrow as pa
import pyarrow.compute as pc

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "code/business_entity_resolution/src"))
sys.path.insert(0, str(REPO / "exploration/p2"))
from translit_map_report import prep, read  # noqa: E402
from ber.config import env  # noqa: E402
from ber.data import unit_hash  # noqa: E402
from ber.normalize.p2_translit import _is_native, learn_canonical_map, learn_junk, learn_token_map  # noqa: E402

QFRAC = 0.1


def jacc(a, b):
    a, b = set(a), set(b)
    return len(a & b) / len(a | b) if (a or b) else 0.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fit", type=float, default=0.3, help="fraction of S1 (by hash) used to learn the maps")
    ap.add_argument("--canon_min_support", type=int, default=50)
    ap.add_argument("--canon_min_precision", type=float, default=0.5)
    ap.add_argument("--junk_min_count", type=int, default=1000)
    a = ap.parse_args()
    t0 = time.time()
    tr = Path(env("BER_DATA_DIR")) / "train"
    ids, names, addrs, country, src = [], [], [], [], []
    for s in (1, 2, 3):
        t = read(tr / f"train_source{s}.tsv", ["entity_id", "business_name", "business_address", "country"])
        ids += t["entity_id"].chunks; names += t["business_name"].chunks; addrs += t["business_address"].chunks
        country += t["country"].chunks; src.append(np.full(t.num_rows, s, np.int8))
    ids, names, addrs, country = map(pa.chunked_array, (ids, names, addrs, country))
    src = np.concatenate(src)
    g = read(tr / "train_ground_truth.tsv", ["source1_entity_id", "matched_entity_ids"])
    lists = pc.split_pattern(g["matched_entity_ids"], ",")
    par = pc.list_parent_indices(lists)
    flat = pc.list_flatten(lists)
    ok = pc.not_equal(flat, "")
    par = pc.filter(par, ok).to_numpy()
    s_rows = pc.index_in(pc.take(g["source1_entity_id"], pa.array(par)), value_set=ids).to_numpy()
    c_rows = pc.index_in(pc.filter(flat, ok), value_set=ids).to_numpy()
    gt_s1 = g["source1_entity_id"].to_numpy(zero_copy_only=False)
    hs = np.fromiter((unit_hash(s, 5) for s in gt_s1), float, len(gt_s1))[par]
    fit = (hs >= QFRAC) & (hs < QFRAC + a.fit)
    held = hs < QFRAC
    rng = np.random.default_rng(0)
    h_idx = np.flatnonzero(held)
    cty = country.to_numpy(zero_copy_only=False)
    perm = h_idx.copy()
    for c in np.unique(cty[s_rows[h_idx]]):                    # random partner within the same country string
        m = cty[s_rows[h_idx]] == c
        perm[m] = rng.permutation(h_idx[m])
    print(f"# Abbreviation map + junk tokens (p2 T10) — generated by exploration/p2/canon_report.py --fit {a.fit} "
          f"--canon_min_support {a.canon_min_support} --canon_min_precision {a.canon_min_precision} "
          f"--junk_min_count {a.junk_min_count}\n")
    print(f"- fit pairs {int(fit.sum()):,} (S1 hash in [{QFRAC}, {QFRAC + a.fit})), held-out pairs {len(h_idx):,} (hash < {QFRAC}); "
          f"load {time.time() - t0:.0f}s\n")
    samp = np.fromiter((unit_hash(x, 9) < 0.3 for x in ids.to_numpy(zero_copy_only=False)), bool, len(ids))
    for field, col in (("name", names), ("addr", addrs)):
        t = time.time()
        take = lambda rows: [prep(x) for x in pc.take(col, pa.array(rows)).to_numpy(zero_copy_only=False)]
        f_idx = np.flatnonzero(fit)
        L = [x.split() for x in take(s_rows[f_idx])]
        R = [x.split() for x in take(c_rows[f_idx])]
        nat = learn_token_map([[w for w in r if _is_native(w)] for r in R], [[w for w in l if w.isascii()] for l in L], 3, 0.5)
        R = [[nat.get(w, w) for w in r] for r in R]
        cmap = learn_canonical_map(L, R, a.canon_min_support, a.canon_min_precision)
        Lc = [[cmap.get(w, w) for w in l] for l in L]
        Rc = [[cmap.get(w, w) for w in r] for r in R]
        # document frequencies on a 30% hash sample of all records (ratios are what matter)
        vals = pc.take(col, pa.array(np.flatnonzero(samp))).to_numpy(zero_copy_only=False)
        s_is1 = src[samp] == 1
        df_l, df_r = Counter(), Counter()
        for v, one in zip(vals, s_is1):
            toks = {cmap.get(w, nat.get(w, w)) for w in prep(v).split()}
            (df_l if one else df_r).update(toks)
        scale = a.fit / 1.0                                    # min_count is defined on the full fit side (90% of S1)
        junk = learn_junk(Lc, Rc, df_l, df_r, max(1, int(a.junk_min_count * scale / 0.9)), 0.01, 0.01)
        del L, R, Lc, Rc, vals
        # held-out evaluation
        HL = [x.split() for x in take(s_rows[h_idx])]
        HR = [[nat.get(w, w) for w in x.split()] for x in take(c_rows[h_idx])]
        RR = [[nat.get(w, w) for w in x.split()] for x in take(c_rows[perm])]
        norm = lambda toks: [cmap.get(w, w) for w in toks if cmap.get(w, w) not in junk] or toks
        out = {}
        for tag, right in (("true", HR), ("random", RR)):
            before = np.array([jacc(l, r) for l, r in zip(HL, right)])
            after = np.array([jacc(norm(l), norm(r)) for l, r in zip(HL, right)])
            d = after - before
            out[tag] = (before.mean(), after.mean(), (d > 0).mean(), (d < 0).mean())
        print(f"## {field}\n")
        print(f"- abbreviation map: {len(cmap)} entries; junk tokens: {len(junk)}  ({time.time() - t:.0f}s)")
        for tag, (b, af, up, dn) in out.items():
            print(f"- held-out {tag:6s} pairs: mean token Jaccard {b:.4f} -> {af:.4f} (+{af - b:.4f}); "
                  f"pairs with higher overlap {up:.2%}, lower {dn:.2%}")
        cnt = Counter(w for r in HR for w in r if w in cmap)
        print("\n| abbreviation | full form | held-out occurrences |\n|---|---|---|")
        for k, v in sorted(cmap.items(), key=lambda kv: -cnt[kv[0]])[:40]:
            print(f"| {k} | {v} | {cnt[k]:,} |")
        print("\n| junk token | fit pairs | hit rate in S1 partner | S1 df (30% sample) | S2/S3 df (30% sample) |\n|---|---|---|---|---|")
        for k, v in sorted(junk.items(), key=lambda kv: -kv[1]["pairs"])[:40]:
            print(f"| {k} | {v['pairs']:,} | {v['hit_rate']} | {v['s1_df']:,} | {v['right_df']:,} |")
        print()
    print(f"_total {time.time() - t0:.0f}s_")


if __name__ == "__main__":
    main()
