"""T04 (p2): quality report of the learned native->Latin token maps (p2_translit), memory-lean (pyarrow).

Protocol (no leakage): the maps are learned from the true pairs of S1 entities with unit_hash(s1, 5) >= QFRAC
(the same split blk_eval uses for fitting), and evaluated on the held-out pairs of the other S1 entities:
  * coverage  = share of native-token occurrences (right side of held-out true pairs) that get a Latin form;
  * accuracy  = share of mapped occurrences whose Latin form appears in the true S1 partner's tokens.
Also: the 30 most frequent learned mappings, and (diagnostic only, never used for any choice) the share of
native-token occurrences in the TEST S2/S3 records that the train-learned map covers.

Usage: python exploration/p2/translit_map_report.py [--fold 0|1] > exploration/p2/translit_map_out.md
"""
from __future__ import annotations

import argparse
import sys
import time
from collections import Counter
from pathlib import Path

import numpy as np
import pyarrow as pa
import pyarrow.compute as pc
import pyarrow.csv as pcsv

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "code/business_entity_resolution/src"))
from ber.config import env  # noqa: E402
from ber.data import unit_hash  # noqa: E402
from ber.normalize.basic import clean  # noqa: E402
from ber.normalize.p2_translit import _digits_to_ascii, _is_native, fold, learn_token_map  # noqa: E402

QFRAC = 0.1
OPTS = pcsv.ReadOptions(block_size=1 << 26)
PARSE = pcsv.ParseOptions(delimiter="\t", quote_char=False)
CONV = pcsv.ConvertOptions(column_types={c: pa.string() for c in
                                         ["entity_id", "business_name", "business_address", "country",
                                          "source1_entity_id", "matched_entity_ids"]}, strings_can_be_null=False)


def read(path, cols):
    return pcsv.read_csv(path, read_options=OPTS, parse_options=PARSE,
                         convert_options=pcsv.ConvertOptions(column_types=CONV.column_types, include_columns=cols))


def prep(s: str) -> str:
    return _digits_to_ascii(clean(s))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fold", type=int, default=1, help="1 = fold Brahmic scripts (as T04_a), 0 = no folding")
    ap.add_argument("--min_support", type=int, default=3)
    ap.add_argument("--min_precision", type=float, default=0.5)
    a = ap.parse_args()
    t0 = time.time()
    d = Path(env("BER_DATA_DIR"))
    tr = d / "train"
    ids, names, addrs = [], [], []
    for src in (1, 2, 3):
        t = read(tr / f"train_source{src}.tsv", ["entity_id", "business_name", "business_address"])
        ids.append(t["entity_id"]); names.append(t["business_name"]); addrs.append(t["business_address"])
    ids = pa.chunked_array([c for x in ids for c in x.chunks])
    names = pa.chunked_array([c for x in names for c in x.chunks])
    addrs = pa.chunked_array([c for x in addrs for c in x.chunks])
    g = read(tr / "train_ground_truth.tsv", ["source1_entity_id", "matched_entity_ids"])
    lists = pc.split_pattern(g["matched_entity_ids"], ",")
    s1 = pc.list_parent_indices(lists)
    flat = pc.list_flatten(lists)
    nonempty = pc.not_equal(flat, "")
    s1_ids = pc.take(g["source1_entity_id"], pc.filter(s1, nonempty))
    c_ids = pc.filter(flat, nonempty)
    s_rows = pc.index_in(s1_ids, value_set=ids).to_numpy()
    c_rows = pc.index_in(c_ids, value_set=ids).to_numpy()
    gt_s1 = g["source1_entity_id"].to_numpy(zero_copy_only=False)       # 2.2M unique S1 ids, hashed once
    held_s1 = np.fromiter((unit_hash(s, 5) < QFRAC for s in gt_s1), bool, len(gt_s1))
    held = held_s1[pc.filter(s1, nonempty).to_numpy()]
    n_records = len(ids)
    del gt_s1, held_s1, s1_ids, c_ids, lists, flat, ids, g
    tables = {}
    print(f"# Learned token maps (p2_translit) — generated by exploration/p2/translit_map_report.py "
          f"--fold {a.fold} --min_support {a.min_support} --min_precision {a.min_precision}\n")
    print(f"- {n_records:,} train records, {len(s_rows):,} true pairs; fit on {int((~held).sum()):,} pairs "
          f"(S1 hash >= {QFRAC}), evaluate on {int(held.sum()):,} held-out pairs  (load {time.time() - t0:.0f}s)\n")

    def native_tokens(s):
        return [fold(t) if a.fold else t for t in s.split() if _is_native(t)]

    for field, col in (("name", names), ("address", addrs)):
        t = time.time()
        right_col = pc.take(col, pa.array(c_rows))
        sel = pc.invert(pc.string_is_ascii(right_col)).to_numpy(zero_copy_only=False)
        idx = np.flatnonzero(sel)
        right_raw = pc.take(right_col, pa.array(idx)).to_numpy(zero_copy_only=False)
        left_raw = pc.take(col, pa.array(s_rows[idx])).to_numpy(zero_copy_only=False)
        R = [native_tokens(prep(x)) for x in right_raw]
        L = [[w for w in prep(x).split() if w.isascii()] for x in left_raw]
        is_held = held[idx]
        fit_idx = np.flatnonzero(~is_held)
        table = learn_token_map([R[i] for i in fit_idx], [L[i] for i in fit_idx], a.min_support, a.min_precision)
        # held-out coverage / accuracy (per native-token occurrence)
        occ = cov = acc = 0
        for i in np.flatnonzero(is_held):
            lt = set(L[i])
            for tok in R[i]:
                occ += 1
                lat = table.get(tok)
                if lat is not None:
                    cov += 1
                    acc += lat in lt
        freq = Counter(tok for i in fit_idx for tok in R[i])
        print(f"## {field}\n")
        print(f"- true pairs whose S2/S3 {field} has native-script tokens: {int(sel.sum()):,} "
              f"({sel.mean():.2%} of all true pairs); fit on {len(fit_idx):,}")
        print(f"- learned map size: {len(table):,} native token types (of {len(freq):,} seen in fit pairs)")
        print(f"- held-out native-token occurrences: {occ:,}; coverage {cov / max(1, occ):.4f}; "
              f"accuracy of mapped (Latin form in the true S1 partner) {acc / max(1, cov):.4f}  ({time.time() - t:.0f}s)\n")
        top = sorted(((freq[k], k, v) for k, v in table.items()), reverse=True)[:30]
        print("| native (folded) | Latin | occurrences in fit pairs |\n|---|---|---|")
        for f_, k, v in top:
            print(f"| {k} | {v} | {f_:,} |")
        print()
        tables[field] = table
        del right_col, right_raw, left_raw, R, L, freq
    del names, addrs
    for field, table in tables.items():
        # test coverage (diagnostic only; never used for any choice)
        te = d / "test"
        if te.exists():
            occ_t = cov_t = rows_t = 0
            for src in (2, 3):
                p = te / f"test_source{src}.tsv"
                if not p.exists():
                    continue
                colname = "business_name" if field == "name" else "business_address"
                vals = read(p, [colname])[colname]
                mask = pc.invert(pc.string_is_ascii(vals))   # non-ASCII rows only
                for x in pc.filter(vals, mask).to_numpy(zero_copy_only=False):
                    toks = native_tokens(prep(x))
                    rows_t += bool(toks)
                    occ_t += len(toks)
                    cov_t += sum(tok in table for tok in toks)
            print(f"- {field} — TEST S2/S3 (diagnostic only): {rows_t:,} records with native {field} tokens, "
                  f"{occ_t:,} occurrences, covered by the train-learned map: {cov_t / max(1, occ_t):.4f}\n")
    print(f"_total {time.time() - t0:.0f}s_")


if __name__ == "__main__":
    main()
