"""Stage-2 stacking on a dense-CV run (p1, T07 step 3): does context of the stage-1 probabilities help?

    nice -n 10 python exploration/p1/dense_stack.py <dense_cv run name>

Stage-2 features per pair, built from out-of-fold stage-1 probabilities only (no labels):
  within the S1 entity:  p, rank, gap to best, second-best, sum p, #p>0.5, #p>0.9, group size
  within the S2/S3 record (competing S1 entities):  rank, best OTHER S1's p (margin), sum p, #p>0.5, size
A LightGBM is trained on one fold's pairs and applied to the other (same folds as stage 1, so every stage-2
score is out-of-fold at both levels). Then decided with one-owner + threshold sweep; macro F0.5 over all S1.
Appends to exploration/p1/dense_stack_out.md.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "code/business_entity_resolution/src"))
sys.path.insert(0, str(REPO / "exploration/p1"))
from ber.config import env  # noqa: E402
from ber.data import load_part  # noqa: E402
from dense_decide import owned, score  # noqa: E402


def group_feats(gid: np.ndarray, p: np.ndarray, prefix: str) -> dict:
    """Rank / best / gap / margin-over-best-other / sums of p within groups `gid` (vectorised)."""
    order = np.lexsort((-p, gid))
    g, v = gid[order], p[order]
    first = np.r_[True, g[1:] != g[:-1]]
    start = np.maximum.accumulate(np.where(first, np.arange(len(g)), 0))
    best = v[start]
    nxt = np.minimum(start + 1, len(v) - 1)
    second = np.where((g[nxt] == g) & (nxt != start), v[nxt], 0.0)
    other_best = np.where(np.arange(len(v)) == start, second, best)
    out = {}
    def put(name, val):
        a = np.empty(len(p), np.float32); a[order] = val; out[f"{prefix}_{name}"] = a
    put("rank", np.arange(len(v)) - start + 1)
    put("gap", best - v)
    put("margin", v - other_best)
    put("second", second)
    codes, _ = pd.factorize(gid)
    for name, w in (("sum", p), ("n05", (p > 0.5).astype(float)), ("n09", (p > 0.9).astype(float)),
                    ("size", np.ones(len(p)))):
        out[f"{prefix}_{name}"] = np.bincount(codes, weights=w)[codes].astype(np.float32)
    return out


def main():
    import lightgbm as lgb
    run = sys.argv[1]
    art = Path(env("BER_ARTIFACTS"))
    oof = pd.read_parquet(art / "dense_cv" / "oof" / f"{run}.parquet")
    li, ri = oof["li"].to_numpy().astype(np.int64), oof["ri"].to_numpy().astype(np.int64)
    y, p, fold = oof["label"].to_numpy(), oof["oof"].to_numpy().astype(np.float64), oof["fold"].to_numpy()
    X = pd.DataFrame({"p": p.astype(np.float32), **group_feats(li, p, "s1"), **group_feats(ri, p, "rec")})
    p2 = np.zeros(len(p))
    params = {"objective": "binary", "learning_rate": 0.1, "num_leaves": 63, "min_data_in_leaf": 200,
              "feature_fraction": 0.9, "bagging_fraction": 0.5, "bagging_freq": 1, "verbose": -1, "seed": 0,
              "num_threads": int(os.environ.get("BER_THREADS", "8"))}
    for k in np.unique(fold):
        tr, te = fold != k, fold == k
        m = lgb.train(params, lgb.Dataset(X[tr].to_numpy(np.float32), y[tr], feature_name=list(X.columns)), 400)
        p2[te] = m.predict(X[te].to_numpy(np.float32))
        imp = pd.Series(m.feature_importance("gain"), index=X.columns).sort_values(ascending=False)
        print(f"fold {k} top features: {imp.head(8).round(0).to_dict()}", flush=True)
    full = load_part(env("BER_DATA_DIR"), "train", cache_dir=art / "cache")
    recs = full.records
    n = len(recs)
    idx = pd.Index(recs["entity_id"].to_numpy())
    ntrue = np.zeros(n, np.int64)
    np.add.at(ntrue, idx.get_indexer(list(full.gt)), [len(v) for v in full.gt.values()])
    s1_rows = np.flatnonzero((recs["source"] == 1).to_numpy())
    ctry = recs["country"].to_numpy()[s1_rows]
    rows = []
    for name, q in (("stage1", p), ("stage2", p2)):
        own = owned(li, ri, q)
        for t in (0.4, 0.5, 0.6, 0.65, 0.7, 0.8):
            f = score(li, y, own[q[own] >= t], ntrue, s1_rows, n)
            rows.append({"model": name, "thr": t, "F0.5": round(float(f.mean()), 5),
                         **{c: round(float(f[ctry == c].mean()), 5) for c in sorted(set(ctry))},
                         **{f"fold{k}": round(float(f[np.isin(s1_rows, li[fold == k])].mean()), 5)
                            for k in np.unique(fold)}})
            print(rows[-1], flush=True)
    text = f"\n## {run}\n\n" + pd.DataFrame(rows).to_string(index=False) + "\n"
    out = REPO / "exploration/p1/dense_stack_out.md"
    if not out.exists():
        out.write_text("# Stage-2 stacking on dense-CV OOF scores (p1) — generated by exploration/p1/dense_stack.py\n")
    with open(out, "a") as fh:
        fh.write(text)
    pd.DataFrame({"li": li.astype(np.int32), "ri": ri.astype(np.int32), "label": y, "fold": fold,
                  "oof": p2.astype(np.float32)}).to_parquet(art / "dense_cv" / "oof" / f"{run}_stack.parquet")
    print(text)


if __name__ == "__main__":
    main()
