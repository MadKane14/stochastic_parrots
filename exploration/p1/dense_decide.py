"""Decision-rule experiments on a dense-CV run's out-of-fold scores (p1, T07 step 3). Seconds per rule.

    python exploration/p1/dense_decide.py <dense_cv run name>

Rules (all after one-owner assignment: each S2/S3 record only for its best-scoring S1):
  thr t        keep owned pairs with p >= t
  ef[a]        expected-F0.5-optimal prefix per S1: sort owned candidates by p (desc), choose k maximising
               1.25 * sum_{i<=k} p_i / (0.25 * E[n_true] + k)     (F0.5 = 1.25 tp / (0.25 n_true + n_pred))
               with E[n_true] = sum of p over ALL the S1's candidates (owned or not) * a, and k = 0 scored as
               P(no true match) = prod(1 - p_i); a > 1 accounts for true pairs the blocker missed.
Macro F0.5 over all train S1 (blocking misses count). Appends to exploration/p1/dense_decide_out.md.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "code/business_entity_resolution/src"))
sys.path.insert(0, str(REPO / "exploration/p1"))
from ber.config import env  # noqa: E402
from ber.data import load_part  # noqa: E402
from dense_cv import fbeta_vec  # noqa: E402


def owned(li, ri, p):
    order = np.lexsort((-p, ri))
    return order[np.r_[True, ri[order][1:] != ri[order][:-1]]]


def score(li, label, keep, ntrue, s1_rows, n):
    tp = np.bincount(li[keep], weights=label[keep], minlength=n)
    npred = np.bincount(li[keep], minlength=n)
    return fbeta_vec(tp[s1_rows], npred[s1_rows], ntrue[s1_rows])


def ef_rule(li, p, own, n, alpha=1.0):
    """Expected-F0.5-optimal prefix per S1 over its owned candidates."""
    ent = np.bincount(li, weights=p, minlength=n) * alpha                   # E[n_true] per S1
    log_none = np.bincount(li, weights=np.log1p(-np.minimum(p, 1 - 1e-9)), minlength=n)
    o = own[np.lexsort((-p[own], li[own]))]                                  # owned, by S1 then p desc
    g = li[o]
    first = np.r_[True, g[1:] != g[:-1]]
    start = np.maximum.accumulate(np.where(first, np.arange(len(o)), 0))
    k = np.arange(len(o)) - start + 1
    csum = np.cumsum(p[o]); csum_start = np.where(start > 0, csum[start - 1], 0.0)
    cp = csum - csum_start
    ef = 1.25 * cp / (0.25 * ent[g] + k)
    best = pd.Series(ef).groupby(g).transform("max").to_numpy()
    kbest = pd.Series(np.where(ef == best, k, 10**9)).groupby(g).transform("min").to_numpy()
    take = (k <= kbest) & (best > np.exp(log_none[g]))
    return o[take]


def main():
    run = sys.argv[1]
    art = Path(env("BER_ARTIFACTS"))
    oof = pd.read_parquet(art / "dense_cv" / "oof" / f"{run}.parquet")
    full = load_part(env("BER_DATA_DIR"), "train", cache_dir=art / "cache")
    recs = full.records
    n = len(recs)
    idx = pd.Index(recs["entity_id"].to_numpy())
    ntrue = np.zeros(n, np.int64)
    np.add.at(ntrue, idx.get_indexer(list(full.gt)), [len(v) for v in full.gt.values()])
    s1_rows = np.flatnonzero((recs["source"] == 1).to_numpy())
    ctry = recs["country"].to_numpy()[s1_rows]
    li, ri = oof["li"].to_numpy().astype(np.int64), oof["ri"].to_numpy().astype(np.int64)
    label, p = oof["label"].to_numpy(), oof["oof"].to_numpy().astype(np.float64)
    own = owned(li, ri, p)
    rows = []
    def add(name, keep):
        f = score(li, label, keep, ntrue, s1_rows, n)
        rows.append({"rule": name, "F0.5": round(float(f.mean()), 5),
                     **{c: round(float(f[ctry == c].mean()), 5) for c in sorted(set(ctry))},
                     "pred_pairs": int(len(keep))})
        print(rows[-1], flush=True)
    for t in (0.4, 0.5, 0.55, 0.6, 0.65, 0.7, 0.75, 0.8):
        add(f"thr {t}", own[p[own] >= t])
    for a in (1.0, 1.03, 1.1):
        add(f"ef alpha={a}", ef_rule(li, p, own, n, a))
    text = f"\n## {run}\n\n" + pd.DataFrame(rows).to_string(index=False) + "\n"
    out = REPO / "exploration/p1/dense_decide_out.md"
    if not out.exists():
        out.write_text("# Decision rules on dense-CV OOF scores (p1) — generated by exploration/p1/dense_decide.py\n")
    with open(out, "a") as fh:
        fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
