"""T03 (p1): compare a test-mode run's predictions per country (France is unseen) with validation runs.

Per country: predicted-empty rate, matches per S1, candidates per S1, and the distribution of each S1's best
candidate score. Validation rows also show the truth (singleton rate, true matches per S1) for reference.

    python exploration/p1/t03_compare.py <test_run_id> <val_run_id> [<val_run_id> ...]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "code/business_entity_resolution/src"))
from ber.config import env  # noqa: E402
from ber.data import load_part  # noqa: E402


def stats(run_id: str, s1_country: pd.Series, gt: dict | None) -> pd.DataFrame:
    art = Path(env("BER_ARTIFACTS")) / "runs" / run_id
    pairs = pd.read_parquet(art / "scored_pairs.parquet", columns=["s1_id", "cand_id", "score"])
    matches = pd.read_csv(art / "matches.tsv", sep="\t", dtype=str)
    ids = s1_country.index
    n_m = matches.groupby("s1_id").size().reindex(ids, fill_value=0)
    n_c = pairs.groupby("s1_id").size().reindex(ids, fill_value=0)
    top = pairs.groupby("s1_id")["score"].max().reindex(ids)
    df = pd.DataFrame({"country": s1_country.to_numpy(), "n_m": n_m.to_numpy(), "n_c": n_c.to_numpy(),
                       "top": top.to_numpy()}, index=ids)
    if gt is not None:
        df["n_true"] = [len(gt.get(s, ())) for s in ids]
    rows = []
    for c, g in df.groupby("country"):
        r = {"run": run_id[:15] + "…" + run_id[-24:], "country": c, "n_s1": len(g),
             "pred_empty": round(float((g.n_m == 0).mean()), 4), "matches/S1": round(float(g.n_m.mean()), 3),
             "cands/S1": round(float(g.n_c.mean()), 1), "no_cands": round(float((g.n_c == 0).mean()), 4),
             "top_p<0.5": round(float((g.top.fillna(0) < 0.5).mean()), 4),
             "top_p_median": round(float(g.top.median()), 3)}
        if "n_true" in g:
            r["true_empty"] = round(float((g.n_true == 0).mean()), 4)
            r["true_matches/S1"] = round(float(g.n_true.mean()), 3)
        rows.append(r)
    return pd.DataFrame(rows)


def main():
    test_id, val_ids = sys.argv[1], sys.argv[2:]
    art = Path(env("BER_ARTIFACTS"))
    out = []
    test = load_part(env("BER_DATA_DIR"), "test", cache_dir=art / "cache")
    out.append(stats(test_id, test.s1.set_index("entity_id")["country"], None))
    if val_ids:
        from ber.eval.harness import DEV_SEED, parse_split
        from ber.eval.splits import make_split, subsample
        full = load_part(env("BER_DATA_DIR"), "train", cache_dir=art / "cache")
        for vid in val_ids:
            rec = json.loads((REPO / "results" / vid.split("_")[1] / f"{vid}.json").read_text())
            base, frac = parse_split(rec["split"])
            _, val = make_split(full, base)
            if frac < 1:
                val = subsample(val, frac, seed=DEV_SEED)
            out.append(stats(vid, val.s1.set_index("entity_id")["country"], val.gt))
    table = pd.concat(out, ignore_index=True)
    text = (f"\n## Test {test_id} vs validation\n\n" + table.to_string(index=False) + "\n")
    path = REPO / "exploration/p1/t03_compare_out.md"
    if not path.exists():
        path.write_text("# Test vs validation prediction stats per country (p1) — generated by exploration/p1/t03_compare.py\n")
    with open(path, "a") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
