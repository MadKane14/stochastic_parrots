"""EDA-lite for T02 (p1). Memory-lean: pyarrow tables + integer ids (runs in < 7 GB RAM).

    python exploration/p1/eda.py [--data data/dataset] [--out exploration/p1/eda_out.md] [--sample 200000]

Every number in eda_out.md comes from this script.
"""
import argparse
import gc
import re
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
import pyarrow as pa
import pyarrow.compute as pc
import pyarrow.csv as pacsv

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "code" / "business_entity_resolution" / "src"))
from ber.normalize.basic import clean  # noqa: E402

OUT: list[str] = []


def emit(s=""):
    print(s, flush=True)
    OUT.append(s)


def table(df: pd.DataFrame) -> str:
    try:
        return df.to_markdown()
    except ImportError:
        return "```\n" + df.to_string() + "\n```"


def read(path: Path) -> pa.Table:
    return pacsv.read_csv(path, read_options=pacsv.ReadOptions(block_size=1 << 26),
                          parse_options=pacsv.ParseOptions(delimiter="\t", quote_char='"', double_quote=True),
                          convert_options=pacsv.ConvertOptions(strings_can_be_null=False,
                                                               column_types={c: pa.string() for c in (
                                                                   "entity_id", "business_name", "business_address", "country",
                                                                   "source1_entity_id", "matched_entity_ids")}))


def int_id(arr) -> np.ndarray:
    """'S2-681193310' -> 2*10^12 + 681193310 (unique across sources)."""
    src = pc.cast(pc.utf8_slice_codeunits(arr, 1, 2), pa.int64()).to_numpy(zero_copy_only=False)
    num = pc.cast(pc.utf8_slice_codeunits(arr, 3), pa.int64()).to_numpy(zero_copy_only=False)
    return src * 10**12 + num


COUNTRIES: list[str] = []


def ccode(arr) -> np.ndarray:
    """Country strings -> small int codes (global, open set; memory-lean)."""
    enc = pc.dictionary_encode(arr).combine_chunks()
    dic = enc.dictionary.to_pylist()
    for c in dic:
        if c not in COUNTRIES:
            COUNTRIES.append(c)
    remap = np.array([COUNTRIES.index(c) for c in dic], dtype=np.int8)
    return remap[enc.indices.to_numpy(zero_copy_only=False)]


def share(arr, pattern) -> float:
    return pc.mean(pc.cast(pc.match_substring_regex(arr, pattern), pa.int8())).as_py()


def count_lines(p: Path) -> int:
    n = 0
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 24), b""):
            n += chunk.count(b"\n")
    return n - 1


def field_stats(t: pa.Table, part: str, src: int) -> dict:
    nm, ad = t["business_name"], t["business_address"]
    return {"part": part, "src": src,
            "name_devanagari": round(share(nm, r"[\x{0900}-\x{097F}]"), 4),
            "name_other_nonlatin": round(share(nm, r"[^\x{0000}-\x{024F}\x{0900}-\x{097F}\x{2000}-\x{20CF}]"), 4),
            "addr_devanagari": round(share(ad, r"[\x{0900}-\x{097F}]"), 4),
            "name_empty": round(share(pc.utf8_trim_whitespace(nm), r"^$"), 4),
            "addr_empty": round(share(pc.utf8_trim_whitespace(ad), r"^$"), 4),
            "name_len_med": float(np.median(pc.utf8_length(nm).to_numpy(zero_copy_only=False))),
            "addr_len_med": float(np.median(pc.utf8_length(ad).to_numpy(zero_copy_only=False))),
            "name_all_upper": round(pc.mean(pc.cast(pc.equal(nm, pc.utf8_upper(nm)), pa.int8())).as_py(), 3),
            "name_has_digit": round(share(nm, r"\d"), 4),
            "name_junk_prefix": round(share(nm, r"^[^\w]"), 4)}


def toks(s):
    return set(clean(s).split())


def digits(s, k):
    return {t for t in re.findall(r"\d+", s) if len(t) >= k}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(ROOT / "data" / "dataset"))
    ap.add_argument("--out", default=str(ROOT / "exploration" / "p1" / "eda_out.md"))
    ap.add_argument("--sample", type=int, default=200000)
    a = ap.parse_args()
    d = Path(a.data)
    t0 = time.time()
    emit("# EDA-lite (p1, T02) — generated by exploration/p1/eda.py\n")

    # ---------- Q1 + Q5/Q6 per file (test first, then dropped) ----------
    size_rows, field_rows, country_vals = [], [], {}
    train = {}
    for part in ("test", "train"):
        for src in (1, 2, 3):
            p = d / part / f"{part}_source{src}.tsv"
            t = read(p)
            vc = {r["values"]: r["counts"] for r in pc.value_counts(t["country"]).to_pylist()}
            size_rows.append({"part": part, "src": src, "rows": t.num_rows, "physical_lines": count_lines(p),
                              "dup_ids": t.num_rows - pc.count_distinct(t["entity_id"]).as_py(), **vc})
            field_rows.append(field_stats(t, part, src))
            for k, v in vc.items():
                country_vals[(part, k)] = country_vals.get((part, k), 0) + v
            if part == "train":
                train[src] = t
            del t
            gc.collect()
    gt = read(d / "train" / "train_ground_truth.tsv")
    emit(f"_load + per-file stats: {time.time() - t0:.0f}s_\n")
    emit("## Q1. Rows per source × country; parse sanity\n")
    emit(table(pd.DataFrame(size_rows).fillna(0).set_index(["part", "src"]).astype(int)))
    emit("\n(rows == physical_lines ⇒ no quoted fields spanning lines)\n")

    s1_ids = int_id(train[1]["entity_id"])
    s1_country = ccode(train[1]["country"])
    gt_s1 = int_id(gt["source1_entity_id"])
    emit(f"- GT rows {gt.num_rows}; S1 rows {len(s1_ids)}; same id set: {np.array_equal(np.sort(gt_s1), np.sort(s1_ids))}")

    # ---------- Q2 ----------
    emit("\n## Q2. Matches per S1 entity\n")
    lists = pc.split_pattern(gt["matched_entity_ids"], ",")
    flat = pc.list_flatten(lists)
    nonempty = pc.not_equal(flat, "")
    parent = pc.list_parent_indices(lists).to_numpy()
    keep = nonempty.to_numpy(zero_copy_only=False)
    pair_s1 = gt_s1[parent[keep]]
    pair_r = int_id(pc.filter(flat, nonempty))
    n_match = np.bincount(parent[keep], minlength=gt.num_rows)
    order = np.argsort(s1_ids)
    pos = order[np.searchsorted(s1_ids[order], gt_s1)]
    g_country = np.array(COUNTRIES, dtype=object)[s1_country[pos]]
    g = pd.DataFrame({"n": n_match, "country": g_country})
    dist = g.assign(bucket=g["n"].clip(upper=8)).pivot_table(index="bucket", columns="country", values="n",
                                                             aggfunc="count", fill_value=0)
    dist["all"] = dist.sum(axis=1)
    emit(table((dist / dist.sum()).round(4)))
    emit(f"\n- singleton rate overall {(g['n'] == 0).mean():.4f}; by country "
         f"{g.groupby('country')['n'].apply(lambda x: round(float((x == 0).mean()), 4)).to_dict()}")
    emit(f"- mean matches per non-singleton S1 {g.loc[g['n'] > 0, 'n'].mean():.3f}; p99 {np.quantile(g['n'], 0.99):.0f}; max {g['n'].max()}")
    is_s2 = pair_r // 10**12 == 2
    emit(f"- GT pairs {len(pair_r)}; share S2 {is_s2.mean():.4f}, S3 {1 - is_s2.mean():.4f}")
    pdf = pd.DataFrame({"s1": pair_s1, "s2": is_s2})
    per = pdf.groupby("s1")["s2"].agg(["sum", "count"])
    emit(f"- among matched S1: ≥1 S2 match {(per['sum'] > 0).mean():.4f}; ≥1 S3 match {(per['sum'] < per['count']).mean():.4f}; "
         f"≥2 S2 matches {(per['sum'] >= 2).mean():.4f}; ≥2 S3 matches {((per['count'] - per['sum']) >= 2).mean():.4f}")

    # ---------- Q3 ----------
    emit("\n## Q3. Right-record ownership\n")
    uniq, cnt = np.unique(pair_r, return_counts=True)
    emit(f"- S2/S3 ids in >1 GT list: {(cnt > 1).sum()} (max owners {cnt.max()})")
    r_ids, r_country = {}, {}
    for src in (2, 3):
        r_ids[src] = int_id(train[src]["entity_id"])
        r_country[src] = ccode(train[src]["country"])
        m = np.isin(r_ids[src], uniq)
        emit(f"- train S{src}: matched to some S1 {m.mean():.4f}; distractors {1 - m.mean():.4f}")
    all_r = np.concatenate([r_ids[2], r_ids[3]])
    all_rc = np.concatenate([r_country[2], r_country[3]])
    emit(f"- GT ids missing from train S2/S3 files: {(~np.isin(uniq, all_r)).sum()}")
    emit(f"- right records per S1 (train): {len(all_r) / len(s1_ids):.2f}; GT pairs per S1: {len(pair_r) / len(s1_ids):.2f}")

    # ---------- Q4 ----------
    emit("\n## Q4. Country label agreement on true pairs\n")
    ro = np.argsort(all_r)
    rc_pairs = all_rc[ro[np.searchsorted(all_r[ro], pair_r)]]
    sc_pairs = s1_country[order[np.searchsorted(s1_ids[order], pair_s1)]]
    emit(f"- same country string on true pairs: {(rc_pairs == sc_pairs).mean():.5f} ({len(pair_r)} pairs)")
    ct = pd.crosstab(pd.Series(sc_pairs, name="S1"), pd.Series(rc_pairs, name="S2/S3"))
    ct.index = [COUNTRIES[i] for i in ct.index]
    ct.columns = [COUNTRIES[i] for i in ct.columns]
    emit(table(ct))
    del rc_pairs, sc_pairs, lists, flat, parent, keep, pdf, per, g, gt, all_rc, r_country, uniq, cnt
    gc.collect()
    for part in ("train", "test"):
        emit(f"- {part} country values (all sources): { {k[1]: v for k, v in country_vals.items() if k[0] == part} }")

    emit("\n## Q5–Q6. Scripts, empty fields, lengths, junk\n")
    emit(table(pd.DataFrame(field_rows).set_index(["part", "src"])))

    # ---------- Q7 ----------
    emit(f"\n## Q7. Overlap signals ({a.sample} sampled true pairs vs random same-country S1×right pairs)\n")
    rng = np.random.default_rng(0)
    idx = rng.choice(len(pair_r), size=min(a.sample, len(pair_r)), replace=False)
    sp_s1, sp_r = pair_s1[idx], pair_r[idx]
    rnd_r = all_r[rng.choice(len(all_r), size=len(idx) * 3, replace=True)]
    need = np.unique(np.concatenate([sp_s1, sp_r, rnd_r]))

    def text_of(t, ids):
        m = np.isin(int_id(t["entity_id"]), ids)
        sub = t.filter(pa.array(m)).to_pandas()
        sub.index = int_id(pa.array(sub["entity_id"]))
        return sub[["business_name", "business_address", "country"]]

    info = pd.concat([text_of(train[s], need) for s in (1, 2, 3)])
    L, R = info.loc[sp_s1], info.loc[sp_r]
    RR = info.loc[rnd_r]

    def stats(Ln, Rn):
        nt = [(toks(x), toks(y)) for x, y in zip(Ln["business_name"], Rn["business_name"])]
        at = [(toks(x), toks(y)) for x, y in zip(Ln["business_address"], Rn["business_address"])]
        out = {"n": len(Ln),
               "name_exact_norm": np.mean([clean(x) == clean(y) for x, y in zip(Ln["business_name"], Rn["business_name"])]),
               "name_share_token": np.mean([bool(x & y) for x, y in nt]),
               "name_jaccard_median": np.median([len(x & y) / max(1, len(x | y)) for x, y in nt]),
               "addr_share_token": np.mean([bool(x & y) for x, y in at]),
               "name_or_addr_share_token": np.mean([bool(n[0] & n[1]) or bool(m[0] & m[1]) for n, m in zip(nt, at)])}
        for k in (1, 3, 5, 6):
            dd = [(digits(x, k), digits(y, k)) for x, y in zip(Ln["business_address"], Rn["business_address"])]
            out[f"digits{k}+_both_present"] = np.mean([bool(x) and bool(y) for x, y in dd])
            out[f"digits{k}+_shared"] = np.mean([bool(x & y) for x, y in dd])
        return out

    cols = {}
    for c in sorted(L["country"].unique()):
        m = (L["country"] == c).values
        cols[f"true:{c}"] = stats(L[m], R[m])
        Lr = L[m]
        rr = RR[RR["country"].values == c].head(int(m.sum()))
        cols[f"random:{c}"] = stats(Lr.head(len(rr)), rr)
    emit(table(pd.DataFrame(cols).round(4)))

    # ---------- Q8 ----------
    emit("\n## Q8a. 20 random true pairs\n")
    for s1, r in zip(sp_s1[:20], sp_r[:20]):
        a1, b1 = info.loc[s1], info.loc[r]
        emit(f"- `{a1['business_name']}` | `{a1['business_address']}` [{a1['country']}]  ⇄  "
             f"`{b1['business_name']}` | `{b1['business_address']}` [S{r // 10**12}, {b1['country']}]")

    emit("\n## Q8b. Hard negatives: identical normalized name, not a match\n")
    ssel = np.sort(rng.choice(len(s1_ids), 300000, replace=False))
    s1n = pd.DataFrame({"id": s1_ids[ssel], "name": pc.take(train[1]["business_name"], pa.array(ssel)).to_pylist()})
    s1n["k"] = s1n["name"].map(clean)
    del info, L, R, RR
    gc.collect()
    n2 = train[2].num_rows
    rsel = np.sort(rng.choice(len(all_r), 2000000, replace=False))
    sel2, sel3 = rsel[rsel < n2], rsel[rsel >= n2] - n2
    rnames = pa.concat_arrays([pc.take(train[2]["business_name"], pa.array(sel2)).combine_chunks(),
                               pc.take(train[3]["business_name"], pa.array(sel3)).combine_chunks()]).to_pylist()
    rn = pd.DataFrame({"rid": np.concatenate([r_ids[2][sel2], r_ids[3][sel3]]), "name_r": rnames})
    rn["k"] = rn["name_r"].map(clean)
    # cap name frequency so the many-to-many join stays small (very common names like chains excluded here)
    s1n = s1n[s1n["k"].map(s1n["k"].value_counts()) <= 3]
    rn = rn[rn["k"].map(rn["k"].value_counts()) <= 20]
    j = s1n.merge(rn, on="k")
    def pkey(s1, r):  # compact int64 key of a (S1, right) pair
        return ((s1 % 10**12) << 32) | ((r // 10**12 - 2) << 31) | (r % 10**12)
    truth = np.sort(pkey(pair_s1, pair_r))
    q = pkey(j["id"].values, j["rid"].values)
    pos_ = np.clip(np.searchsorted(truth, q), 0, len(truth) - 1)
    j["match"] = truth[pos_] == q
    emit(f"- sampled pairs with identical normalized name: {len(j)}; true-match rate {j['match'].mean():.4f} "
         f"(sample: 300k S1 × 2M right; names with freq ≤3 / ≤20 in the samples)")
    neg = j[~j["match"]].head(20)
    need2 = np.unique(np.concatenate([neg["id"].values, neg["rid"].values]))
    info2 = pd.concat([text_of(train[s], need2) for s in (1, 2, 3)])
    for s1, r in zip(neg["id"], neg["rid"]):
        a1, b1 = info2.loc[s1], info2.loc[r]
        emit(f"- `{a1['business_name']}` | `{a1['business_address']}` [{a1['country']}]  ⇄  "
             f"`{b1['business_name']}` | `{b1['business_address']}` [S{r // 10**12}, {b1['country']}]")

    emit("\n## Extra. Name-token document frequency (300k-name sample per train source)\n")
    del train, r_ids, all_r, pair_s1, pair_r, s1n, rn, j, truth
    gc.collect()
    train = {s_: read(d / "train" / f"train_source{s_}.tsv").select(["business_name"]) for s_ in (1, 2, 3)}
    names = pd.Series(sum((pc.take(train[s]["business_name"],
                                   pa.array(rng.choice(train[s].num_rows, 300000, replace=False))).to_pylist()
                           for s in (1, 2, 3)), []))
    tk = names.map(clean).str.split()
    vc = tk.explode().value_counts()
    emit(f"- distinct tokens in 900k names: {len(vc)}; median tokens/name {tk.map(len).median()}")
    emit(f"- share of names whose rarest token has df ≤ 100 in this sample: "
         f"{tk.map(lambda ts: bool(ts) and min(vc[t] for t in ts) <= 100).mean():.4f}")
    emit(f"- top 40 tokens: {vc.head(40).to_dict()}")
    emit(f"\n_total runtime {time.time() - t0:.0f}s_")
    Path(a.out).write_text("\n".join(OUT) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
