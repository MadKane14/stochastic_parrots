"""Candidate pruning study (p1): how small can candidate_pairs.tsv get? (organizer update, docs/organizer_updates.md)

A cheap stage-1 model (LightGBM, few trees, a dozen cheap features) scores the blocker's candidates out-of-fold;
each S1 keeps its top-m candidates plus, from the reverse view, each S2/S3 record keeps its top-r S1 (so records
that belong to this S1 but rank low among its many candidates survive). The final model's out-of-fold scores
(a dense-CV run) are then decided on the survivors only (one owner per record, threshold t).
Reports cands/S1 (mean/p95/max), true pairs kept, and final macro F0.5 vs no pruning.

    nice -n 10 python exploration/p1/prune_eval.py <features parquet in $BER_ARTIFACTS/dense_cv> <dense_cv run name>
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "code/business_entity_resolution/src"))
sys.path.insert(0, str(REPO / "exploration/p1"))
from ber.config import env  # noqa: E402
from ber.data import load_part  # noqa: E402
from dense_decide import owned, score  # noqa: E402

CHEAP = ["blk_0_score", "blk_0_rank", "f_p1_name_tset", "f_p1_addr_tset", "f_p1_idf_n_jacc", "f_p1_idf_w_jacc",
         "f_p1_num_shared", "f_p1_num_first_eq", "f_p1_grp_s1_key_rank", "f_p1_grp_rec_key_rank",
         "f_p1_grp_s1_key_margin", "f_p1_grp_rec_key_margin"]


def topk_mask(gid, s, k):
    order = np.lexsort((-s, gid))
    g = gid[order]
    first = np.r_[True, g[1:] != g[:-1]]
    start = np.maximum.accumulate(np.where(first, np.arange(len(g)), 0))
    m = np.zeros(len(s), bool)
    m[order[(np.arange(len(g)) - start) < k]] = True
    return m


def main():
    import lightgbm as lgb
    feat_file, run = sys.argv[1], sys.argv[2]
    art = Path(env("BER_ARTIFACTS"))
    cols = ["s1_id", "ri", "label"] + CHEAP
    df = pd.read_parquet(art / "dense_cv" / feat_file, columns=cols)
    oof = pd.read_parquet(art / "dense_cv" / "oof" / f"{run}.parquet")
    li, ri = df["s1_id"].to_numpy().astype(np.int64), df["ri"].to_numpy().astype(np.int64)
    assert (li == oof["li"].to_numpy()).all() and (ri == oof["ri"].to_numpy()).all(), "row order mismatch"
    y, fold, p = df["label"].to_numpy(), oof["fold"].to_numpy(), oof["oof"].to_numpy().astype(np.float64)
    X = df[CHEAP].to_numpy(np.float32)
    del df
    q = np.zeros(len(y))
    params = {"objective": "binary", "learning_rate": 0.2, "num_leaves": 31, "min_data_in_leaf": 200,
              "bagging_fraction": 0.3, "bagging_freq": 1, "verbose": -1, "seed": 0,
              "num_threads": int(os.environ.get("BER_THREADS", "8"))}
    for k in np.unique(fold):
        tr = fold != k
        m = lgb.train(params, lgb.Dataset(X[tr], y[tr]), 60)
        q[fold == k] = m.predict(X[fold == k])
    full = load_part(env("BER_DATA_DIR"), "train", cache_dir=art / "cache")
    recs = full.records
    n = len(recs)
    idx = pd.Index(recs["entity_id"].to_numpy())
    ntrue = np.zeros(n, np.int64)
    np.add.at(ntrue, idx.get_indexer(list(full.gt)), [len(v) for v in full.gt.values()])
    s1_rows = np.flatnonzero((recs["source"] == 1).to_numpy())
    rows = []
    def evaluate(name, keep_mask, t=0.7):
        sel = np.flatnonzero(keep_mask)
        o = sel[owned(li[sel], ri[sel], p[sel])]
        f = score(li, y, o[p[o] >= t], ntrue, s1_rows, n)
        nc = np.bincount(li[sel], minlength=n)[s1_rows]
        rows.append({"pruning": name, "cands_mean": round(float(nc.mean()), 2), "p95": float(np.quantile(nc, .95)),
                     "max": int(nc.max()), "true_kept": round(float(y[sel].sum() / y.sum()), 5),
                     "F0.5@0.7": round(float(f.mean()), 5)})
        print(rows[-1], flush=True)
    evaluate("none (blocker)", np.ones(len(y), bool))
    for m_s1, r_rec in ((3, 1), (5, 1), (5, 2), (8, 1), (8, 2), (10, 2), (12, 2), (15, 3)):
        evaluate(f"top{m_s1}/S1 + top{r_rec}/record", topk_mask(li, q, m_s1) | topk_mask(ri, q, r_rec))
    for thr in (0.001, 0.005, 0.02):
        evaluate(f"q >= {thr}", q >= thr)
    text = f"\n## {run} (stage-1: LightGBM 60 trees on {len(CHEAP)} cheap features, out-of-fold)\n\n" + \
        pd.DataFrame(rows).to_string(index=False) + "\n"
    out = REPO / "exploration/p1/prune_eval_out.md"
    if not out.exists():
        out.write_text("# Candidate pruning study (p1) — generated by exploration/p1/prune_eval.py\n")
    with open(out, "a") as fh:
        fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
