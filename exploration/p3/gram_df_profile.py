"""T05 (p3): how selective are char n-grams of the de-spaced name at full train density?

Per country-string group (full train, all S1 + S2/S3, normalized by the config's normalizer): n-grams per S1 name,
how many of them have in-group df <= max_df (= indexed by p3_chargram), and the postings an S1 query touches
(sum of right-side df over its indexed grams = work of the sparse product) — for several max_df caps and n-gram sets.

Usage (repo root, after blk_union.py has cached the normalized records):
    python exploration/p3/gram_df_profile.py --config code/business_entity_resolution/configs/exp/p3/T05_cg_name.yaml \
        --out exploration/p3/gram_df_profile_out.md
"""
from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from blk_union import load  # noqa: E402  (also puts src/ and exploration/p1 on sys.path)
from ber.blocking.p3_chargram import char_codes, gram_keys  # noqa: E402
from ber.config import load_config  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--field", default="name_norm")
    ap.add_argument("--max_len", type=int, default=40)
    ap.add_argument("--caps", default="300,1000,3000,10000,30000")
    ap.add_argument("--nq", type=int, default=20000, help="S1 queries sampled per group")
    ap.add_argument("--out", default="exploration/p3/gram_df_profile_out.md")
    a = ap.parse_args()
    recs, _, _ = load(load_config(a.config), 1.0)
    caps = [int(c) for c in a.caps.split(",")]
    rows_out = []
    for ng in ((3, 4), (4,), (3,)):
        for g in pd.unique(recs["country"]):
            rows = np.flatnonzero((recs["country"] == g).to_numpy())
            s1 = (recs["source"].to_numpy()[rows] == 1)
            o, c = char_codes(recs[a.field].iloc[rows].reset_index(drop=True), a.max_len)
            r, k = gram_keys(o, c, np.arange(len(rows)), ng)
            del o, c
            col, uniq = pd.factorize(k)
            del k
            df = np.bincount(col, minlength=len(uniq))
            df_right = np.bincount(col[~s1[r]], minlength=len(uniq))
            q = np.random.default_rng(0).choice(np.flatnonzero(s1), size=min(a.nq, int(s1.sum())), replace=False)
            m = np.isin(r, q)
            cq, n_s1 = col[m], int(s1.sum())
            row = {"ngrams": "+".join(map(str, ng)), "group": g, "records": len(rows), "S1": n_s1,
                   "distinct grams": len(uniq), "grams/S1": round(m.sum() / len(q), 1)}
            for cap in caps:
                keep = df[cq] <= cap
                row[f"indexed/S1 @{cap}"] = round(keep.sum() / len(q), 1)
                row[f"postings/S1 @{cap}"] = int(df_right[cq][keep].sum() / len(q))
            rows_out.append(row)
            print(row, flush=True)
            del r, col, df, df_right, m
    import blk_eval as be
    text = (f"\n## Run {dt.datetime.now():%Y-%m-%d %H:%M} — config={a.config} field={a.field} max_len={a.max_len} "
            f"(full train, {a.nq} sampled S1 per group)\n\n" + be.md_table(rows_out) + "\n")
    out = Path(a.out)
    if not out.exists():
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("# Char n-gram selectivity at full train density — generated by exploration/p3/gram_df_profile.py\n")
    with open(out, "a", encoding="utf-8") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
